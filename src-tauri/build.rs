use std::{env, fs, path::Path};
mod command_inventory;
#[allow(dead_code)]
#[path = "src/claude_skills/pack_rules.rs"]
mod pack_rules;

// The app_commands token group is consumed by Rust and the restricted build lexer.
fn app_manifest() -> tauri_build::AppManifest {
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=src/app_commands.rs");
    println!("cargo:rerun-if-changed=command_inventory.rs");
    let source = fs::read_to_string("src/lib.rs").expect("read app command registration");
    let inventory = command_inventory::parse_commands(&source, "app_commands")
        .expect("parse app command registration without omissions");
    let names: std::collections::BTreeSet<_> = inventory.iter().cloned().collect();
    let commands: Vec<&'static str> = inventory.into_iter()
        .map(|name| Box::leak(name.into_boxed_str()) as &'static str).collect();
    let permissions = names.iter().map(|name| {
        format!("    \"allow-{}\",\n", name.replace('_', "-"))
    }).collect::<String>();
    let local_set = format!(
        "# Generated by build.rs from src/lib.rs. Do not edit.\n\n[[set]]\nidentifier = \"app-local\"\ndescription = \"All registered commands for the local primary app webviews.\"\npermissions = [\n{permissions}]\n"
    );
    fs::create_dir_all("permissions").expect("create app permissions directory");
    let path = Path::new("permissions/app-local.toml");
    if fs::read_to_string(path).ok().as_deref() != Some(local_set.as_str()) {
        fs::write(path, local_set).expect("write local app permissions");
    }
    tauri_build::AppManifest::new()
        .commands(Box::leak(commands.into_boxed_slice()))
        .permissions_path_pattern("permissions/app-local.toml")
}

fn scan(root: &Path, dir: &Path, files: &mut Vec<(String, std::path::PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut entries: Vec<_> = fs::read_dir(dir)
        .expect("read Claude pack")
        .map(Result::unwrap)
        .collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let path = entry.path();
        let name = entry.file_name();
        if pack_rules::excluded_part(&name.to_string_lossy()) {
            continue;
        }
        let kind = entry.file_type().expect("pack file type");
        assert!(
            !kind.is_symlink(),
            "symlink in Claude pack: {}",
            path.display()
        );
        if kind.is_dir() {
            scan(root, &path, files);
        } else if kind.is_file() {
            println!("cargo:rerun-if-changed={}", path.display());
            files.push((
                path.strip_prefix(root)
                    .unwrap()
                    .to_string_lossy()
                    .replace('\\', "/"),
                path,
            ));
        }
    }
}
fn main() {
    let root = Path::new("../skills/claude")
        .canonicalize()
        .expect("Claude pack");
    let mut files = Vec::new();
    scan(&root, &root, &mut files);
    // Top-level README is documentation, not a manifest-managed payload.
    files.retain(|(rel, _)| rel != "README.md");
    // Per-skill `.packignore`: personal or machine-bound files never enter the
    // embedded pack. sync_claude_skills.py keeps them out of the manifest with
    // the same rules, so validate_pack still sees one identical set.
    files.retain(|(rel, _)| {
        let Some((skill, inner)) = rel.split_once('/') else {
            return true;
        };
        let rules = fs::read_to_string(root.join(skill).join(pack_rules::PACKIGNORE))
            .map(|text| pack_rules::packignore_rules(&text))
            .unwrap_or_default();
        !pack_rules::packignored(inner, &rules)
    });
    let cli = Path::new("../scripts/mycmux_agent_cli.py")
        .canonicalize()
        .expect("agent CLI");
    println!("cargo:rerun-if-changed={}", cli.display());
    println!("cargo:rerun-if-changed=src/claude_skills/pack_rules.rs");
    let mut code = String::from("pub static PACK_FILES: &[(&str, &[u8])] = &[\n");
    for (rel, path) in files {
        code.push_str(&format!(
            "    ({rel:?}, include_bytes!({:?})),\n",
            path.to_str().unwrap()
        ));
    }
    code.push_str(&format!(
        "];\npub static PACK_CLI: &[u8] = include_bytes!({:?});\n",
        cli.to_str().unwrap()
    ));
    code.push_str(&format!(
        "pub static PACK_MANIFEST: &[u8] = include_bytes!({:?});\n",
        root.join("manifest.json").to_str().unwrap()
    ));
    fs::write(
        Path::new(&env::var_os("OUT_DIR").unwrap()).join("claude_skills_pack.rs"),
        code,
    )
    .expect("embed Claude pack");
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(app_manifest()))
        .expect("build Tauri app with command ACL")
}
